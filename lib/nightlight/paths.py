"""Every path this touches, in one place."""

from __future__ import annotations

import os
from pathlib import Path

APP = "nightlight"

HOME = Path.home()
CONFIG_DIR = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))
STATE_HOME = Path(os.environ.get("XDG_STATE_HOME", HOME / ".local/state"))

SETTINGS_PATH = CONFIG_DIR / APP / "config.json"
# omarchy-nightlight-auto, the plugin this one grew out of. Same settings
# format, so its config is adopted rather than making the user start over.
LEGACY_SETTINGS_PATH = CONFIG_DIR / "nightlight-auto" / "config.json"

STATE_DIR = STATE_HOME / APP
MODE_PATH = STATE_DIR / "mode"
MANUAL_TEMP_PATH = STATE_DIR / "manual_temp"
CONSENT_PATH = STATE_DIR / "consent.json"
# The colour last sent to the keyboard, so the per-minute sync can skip asusctl.
KEYBOARD_STATE_PATH = STATE_DIR / "keyboard.json"
KEYBOARD_LOCK_PATH = STATE_DIR / "keyboard.lock"
# Omarchy copies the active theme here; keyboard.rgb is its keyboard colour.
THEME_KEYBOARD_RGB = STATE_HOME / "omarchy" / "current" / "theme" / "keyboard.rgb"

HYPRSUNSET_CONF = CONFIG_DIR / "hypr" / "hyprsunset.conf"
PRE_BACKUP = HYPRSUNSET_CONF.with_name(f"hyprsunset.conf.pre-{APP}")
HYPRSUNSET_UNIT = "hyprsunset.service"

REPO = Path(__file__).resolve().parents[2]
CLI = REPO / "bin" / APP
BIN_LINK = HOME / ".local" / "bin" / APP
UNIT_DIR = CONFIG_DIR / "systemd" / "user"
UNITS = (f"{APP}.service", f"{APP}.timer")
HOOK_PATH = CONFIG_DIR / "omarchy" / "hooks" / "post-boot.d" / f"{APP}.sh"
THEME_HOOK_PATH = CONFIG_DIR / "omarchy" / "hooks" / "theme-set.d" / f"{APP}.sh"

MARKER = f"# generated by {APP}"
